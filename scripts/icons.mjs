#!/usr/bin/env node
// Build src/ui/icons.generated.ts from the web app's icon table
// (packages/client/components/ui/icons/drawings.ts: Hugeicons, MIT), so the
// phone draws exactly the same icons.
//   node scripts/icons.mjs <path to drawings.ts>
// Get the file with:
//   git -C ../web show origin/beta:packages/client/components/ui/icons/drawings.ts > drawings.ts
import { readFileSync, writeFileSync } from "node:fs";

const source = readFileSync(process.argv[2], "utf8");
const table = {};
const entry = /^\s+("?[a-z0-9-]+"?):\s*\n?\s*'([^']*)'/gm;
let m;
while ((m = entry.exec(source))) table[m[1].replace(/"/g, "")] = m[2];

const ATTRS = new Set([
  "d", "cx", "cy", "r", "rx", "ry", "x", "y", "width", "height", "x1", "y1", "x2", "y2", "points",
  "stroke-linecap", "stroke-linejoin", "fill", "stroke", "class", "fill-rule", "clip-rule", "transform",
]);
const out = {};
for (const [name, markup] of Object.entries(table)) {
  const shapes = [];
  const tag = /<(path|circle|rect|line|ellipse|polyline|polygon)\b([^>]*?)\/?>/g;
  let t;
  while ((t = tag.exec(markup))) {
    const attrs = {};
    const attr = /([a-z-]+)=(?:"([^"]*)"|([^\s/>]+))/g;
    let a;
    while ((a = attr.exec(t[2]))) {
      if (!ATTRS.has(a[1])) continue;
      attrs[a[1]] = a[2] ?? a[3];
    }
    const shape = { t: t[1] };
    for (const [k, v] of Object.entries(attrs)) {
      if (k === "stroke") {
        if (v !== "currentColor") shape.stroke = v;
      } else if (k === "fill") {
        if (v === "currentColor") shape.fill = "current";
      } else if (k === "class") {
        if (v.includes("z-shape")) shape.shape = 1;
      } else if (k === "stroke-linecap") shape.cap = v;
      else if (k === "stroke-linejoin") shape.join = v;
      else if (k === "fill-rule" || k === "clip-rule") shape.rule = v;
      else shape[k] = v;
    }
    shapes.push(shape);
  }
  out[name] = shapes;
}

const names = Object.keys(out).sort();
const body = names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(out[n])},`).join("\n");
writeFileSync(
  "src/ui/icons.generated.ts",
  `// Generated by scripts/icons.mjs from the web app's icon table (Hugeicons, MIT). Do not edit.\nexport type IconShape = {\n  t: "path" | "circle" | "rect" | "line" | "ellipse" | "polyline" | "polygon";\n  shape?: 1;\n  fill?: "current";\n  stroke?: string;\n  cap?: "round" | "square" | "butt";\n  join?: "round" | "bevel" | "miter";\n  rule?: "evenodd" | "nonzero";\n  [attr: string]: string | number | undefined;\n};\n\nexport const ICONS = {\n${body}\n} as const satisfies Record<string, readonly IconShape[]>;\n\nexport type IconName = keyof typeof ICONS;\n`,
);
console.log(`${names.length} icons`);
